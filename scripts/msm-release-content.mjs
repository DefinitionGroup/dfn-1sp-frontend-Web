import assert from 'node:assert/strict';
import {mkdirSync, readFileSync, writeFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {getCliClient} from 'sanity/cli';

const projectId = 'wu6i3y0h';
const dataset = 'production';
const client = getCliClient({apiVersion: '2025-09-16'}).withConfig({projectId, dataset, useCdn: false, perspective: 'raw'});
const folder = 'EXPORT/msm-release-2026-10-04';
const planPath = `${folder}/plan.json`;
const apply = process.env.MSM_RELEASE_APPLY === '1';
const descriptions = {
  en: {
    cases: 'Explore MSM.digital projects across communications, channel marketing, AR/VR and technology.',
    disclaimer: 'Company information, contact details and legal notices for MSM.digital.',
    'privacy-policy': 'Information about personal data processing and privacy at MSM.digital.',
  },
  de: {
    cases: 'Entdecke Projekte von MSM.digital aus Kommunikation, Channel Marketing, AR/VR und Technologie.',
    disclaimer: 'Unternehmensangaben, Kontaktdaten und rechtliche Hinweise zu MSM.digital.',
    'privacy-policy': 'Informationen zur Verarbeitung personenbezogener Daten und zum Datenschutz bei MSM.digital.',
  },
};

function findHeroImage(page) {
  const hero = page.content?.find(block => ['oneSPHeader', 'servicesHeroWithBadge'].includes(block._type));
  if (!hero) return undefined;
  const candidates = [hero.backgroundImage, hero.image, hero.media, hero.backgroundVideo, hero.video];
  for (const candidate of candidates) {
    const asset = candidate?.asset || candidate;
    if (!asset?.secure_url?.startsWith('https://res.cloudinary.com/')) continue;
    const fields = ['_type', 'public_id', 'secure_url', 'resource_type', 'format', 'width', 'height', 'version'];
    return {_type: 'cloudinaryImage', asset: Object.fromEntries(fields.filter(key => asset[key] !== undefined).map(key => [key, asset[key]]))};
  }
}

if (apply) {
  const plan = JSON.parse(readFileSync(planPath, 'utf8'));
  assert.equal(plan.projectId, projectId); assert.equal(plan.dataset, dataset);
  const backup = readFileSync(plan.backup);
  assert.equal(createHash('sha256').update(backup).digest('hex'), plan.backupSha256);
  const current = await client.getDocuments(plan.changes.map(change => change.id));
  for (const [index, change] of plan.changes.entries()) {
    assert.equal(current[index]?._rev, change.revision, `${change.id} changed; prepare again.`);
    assert.equal(current[index]?.channel, 'msmWeb');
  }
  let transaction = client.transaction();
  for (const change of plan.changes) transaction = transaction.patch(change.id, patch => patch.ifRevisionId(change.revision).set(change.set));
  const receipt = await transaction.commit();
  const after = await client.getDocuments(plan.changes.map(change => change.id));
  for (const [index, change] of plan.changes.entries()) {
    for (const [field, value] of Object.entries(change.set)) assert.deepEqual(after[index][field], value);
    const before = JSON.parse(backup).find(document => document._id === change.id);
    for (const field of Object.keys(before).filter(field => !field.startsWith('_') && !Object.hasOwn(change.set, field))) assert.deepEqual(after[index][field], before[field]);
  }
  writeFileSync(`${folder}/after.json`, JSON.stringify(after, null, 2), {mode: 0o600});
  writeFileSync(`${folder}/receipt.json`, JSON.stringify({transactionId: receipt.transactionId, updated: plan.changes.map(change => change.id)}, null, 2), {mode: 0o600});
  console.log(JSON.stringify({mode: 'applied', transactionId: receipt.transactionId, documents: after.length, homepages: after.filter(page => page.isHomepage).map(page => ({id: page._id, blocks: page.content.map(block => block._type)}))}));
} else {
  const pages = await client.fetch('*[_type == "page" && channel == "msmWeb"] | order(_id asc)');
  const changes = [];
  for (const page of pages) {
    const metadata = {...page.metadata, _type: 'metadata'};
    metadata.title ||= `${page.title} | MSM.digital`;
    if (!metadata.description || metadata.description.includes('[autogenerated excerpt')) metadata.description = descriptions[page.language]?.[page.slug?.current] || metadata.description;
    metadata.openGraphTitle ||= metadata.title;
    metadata.openGraphDescription ||= metadata.description;
    metadata.openGraphImage ||= metadata.image || findHeroImage(page);
    // Undefined values are not persisted; the renderer supplies the branded fallback image.
    const cleanMetadata = JSON.parse(JSON.stringify(metadata));
    const set = {};
    if (JSON.stringify(cleanMetadata) !== JSON.stringify(page.metadata)) set.metadata = cleanMetadata;
    if (page.isHomepage && page.content?.some(block => block._type === 'globeComponent')) set.content = page.content.filter(block => block._type !== 'globeComponent');
    if (Object.keys(set).length) changes.push({id: page._id, revision: page._rev, set});
  }
  assert.equal(pages.filter(page => page.isHomepage && !page._id.startsWith('drafts.')).length, 2);
  mkdirSync(folder, {recursive: true});
  const backup = `${folder}/before-${Date.now()}.json`;
  const backupText = JSON.stringify(pages, null, 2);
  writeFileSync(backup, backupText, {mode: 0o600});
  assert.deepEqual(JSON.parse(readFileSync(backup, 'utf8')), pages);
  const backupSha256 = createHash('sha256').update(backupText).digest('hex');
  writeFileSync(planPath, JSON.stringify({projectId, dataset, backup, backupSha256, changes}, null, 2), {mode: 0o600});
  console.log(JSON.stringify({mode: 'dry-run', projectId, dataset, backup, backupSha256, documents: changes.length, existingDrafts: pages.filter(page => page._id.startsWith('drafts.')).map(page => page._id), changes: changes.map(change => ({id: change.id, fields: Object.keys(change.set), sharingImage: Boolean(change.set.metadata?.openGraphImage), removedGlobe: Boolean(change.set.content)}))}));
}
